  createLevel() {
    const pads = this.platforms.map((p, i) => ({
      x: p[0] + p[2] / 2, y0: p[1], y: p[1], w: p[2],
      a: 0, f: 0, ph: 0, fin: i === this.platforms.length - 1
    }));
    this.movingPlatforms.forEach(p => pads.push({
      x: p[0] + p[2] / 2, y0: p[1], y: p[1], w: p[2],
      a: p[3], f: p[4], ph: p[5], moving: true, fin: false
    }));
    const stars = Array.from({length:47},(_,i)=>({
      x:180+i*265,y:210+Math.sin(i*1.8)*65,g:0
    }));
    const hazards = this.spikes.map(p=>({type:'spike',x:p[0],y:p[1],w:p[2],h:p[3]}));
    this.saws.forEach(s=>hazards.push({
      type:'saw',x:s[0],y:s[1],r:s[2],baseY:s[1],range:s[3],speed:s[4],phase:s[5]
    }));
    this.hazards = hazards;
    this.update(0);
    return {pads,stars,hazards,world:this};
  }

  update(seconds) {
    this.hazards.forEach(h=>{
      if(h.type==='saw')h.y=h.baseY+Math.sin(seconds*h.speed+h.phase)*h.range;
    });
  }
